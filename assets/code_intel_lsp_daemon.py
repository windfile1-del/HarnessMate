#!/usr/bin/env python3
"""Vega Safe Phase 5 - language server daemon.

Started inside the authoritative execution mirror by the supervised Linux
transport or the legacy Termux bridge, never with a model-supplied executable.
Lives in its own session so it can be torn down as a whole process group.

Usage (argv is generated by the trusted helper, never by the model):
  lsp_daemon.py --socket <unix socket> --root-uri <file://mirror/project>
                --server <kotlin|java|python|typescript|javascript>
                --session <key>

Wire protocol on the socket (one request per connection, newline framed):
  {"action":"ping"}                                  -> pong
  {"action":"stop"}                                  -> stopped
  {"action":"request","method":...,"params":{...}}   -> JSON-RPC response
"""

import argparse
import json
import os
import select
import signal
import socket
import subprocess
import sys
import threading
import time
import traceback
import hmac
import urllib.request
import tempfile
import shutil
from urllib.parse import unquote, urlparse

MAX_FRAME_BYTES = 1024 * 1024
MAX_STDERR_BYTES = 16 * 1024

# Allowlist: a language maps to a fixed executable name and argv. The model can
# never influence this table, and an unavailable server fails closed.
SERVER_ALLOWLIST = {
    'kotlin': [['kotlin-language-server']],
    # Only an already-installed, trusted executable may be selected.  In
    # particular, do not fall back to a jar relative to an arbitrary cwd.
    'java': [['jdtls']],
    'python': [['pyright-langserver', '--stdio'], ['pylsp']],
    'typescript': [['typescript-language-server', '--stdio']],
    'javascript': [['typescript-language-server', '--stdio']],
}


class ServerHandles:
    def __init__(self):
        self.process = None
        self.stderr_lines = []
        self.stderr_bytes = 0

    def drain(self):
        process = self.process
        if process is None or process.stderr is None:
            return
        while True:
            try:
                chunk = process.stderr.read1(4096)
            except (OSError, ValueError):
                break
            if not chunk:
                break
            if self.stderr_bytes < MAX_STDERR_BYTES:
                remaining = MAX_STDERR_BYTES - self.stderr_bytes
                kept = chunk[:remaining]
                self.stderr_lines.append(kept.decode('utf-8', errors='replace'))
                self.stderr_bytes += len(kept)


class LanguageServer:
    def __init__(self, server_id, root_uri, source_root=None):
        self.server_id = server_id
        self.root_uri = root_uri
        self.execution_root = root_path_from_uri(root_uri)
        self.source_root = os.path.realpath(source_root) if source_root else self.execution_root
        self.handles = ServerHandles()
        self.process = None
        self.process_group_id = None
        self.request_id = 0
        self._io_lock = threading.RLock()
        self._write_lock = threading.Lock()
        # A stop/abort request is an in-band cancellation token for every
        # active stdio exchange. It is checked by read_frame itself, not only
        # by the outer socket handler, so a partial header/body cannot keep a
        # request worker alive until its ordinary deadline.
        self._stop_lock = threading.Lock()
        self._cancel_event = threading.Event()
        self._reply_condition = threading.Condition()
        self._responses = {}
        self._diagnostics = {}
        self._documents = {}
        self._capabilities = {}
        self._reader_error = None
        self._reader_thread = None
        self._stderr_thread = None
        self._storage = None

    def start(self):
        if self.execution_root is None or self.source_root is None or not os.path.isdir(self.source_root):
            return False, 'LSP_EXECUTION_ROOT_INVALID'
        if self.execution_root != self.source_root and not self.execution_root.startswith(self.source_root + os.sep):
            return False, 'LSP_EXECUTION_ROOT_INVALID'
        candidates = SERVER_ALLOWLIST.get(self.server_id)
        if not candidates:
            return False, 'LSP_SERVER_UNKNOWN: ' + str(self.server_id)
        last_error = ''
        for candidate in candidates:
            resolved = shutil_which(candidate[0])
            if resolved is None:
                last_error = 'LSP_SERVER_NOT_ON_PATH: ' + candidate[0]
                continue
            try:
                argv = list(candidate)
                argv[0] = resolved
                self.process = subprocess.Popen(
                    argv,
                    stdin=subprocess.PIPE,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    start_new_session=True,
                    # Both daemon and language server are rooted in the P3
                    # persistent mirror, never in the Android/app cwd.
                    cwd=self.execution_root,
                )
            except OSError as error:
                last_error = 'LSP_SPAWN_FAILED: %s' % error
                continue
            self.handles.process = self.process
            self._storage = tempfile.mkdtemp(prefix='vega-lsp-state-')
            try:
                self.process_group_id = os.getpgid(self.process.pid)
            except (OSError, AttributeError):
                self.process_group_id = self.process.pid
            self._stderr_thread = threading.Thread(target=self.handles.drain, daemon=True)
            self._reader_thread = threading.Thread(target=self._read_messages, daemon=True)
            self._stderr_thread.start()
            self._reader_thread.start()
            reply = self.request('initialize', {
                'processId': os.getpid(),
                'rootUri': self.root_uri,
                'workspaceFolders': [{'uri': self.root_uri, 'name': 'main'}],
                'initializationOptions': {'storagePath': self._storage} if self.server_id == 'kotlin' else {},
                # Each session has one immutable project root. Advertising dynamic
                # folder support prevents Pyright from initializing its settings
                # until a folder-change event this client never sends.
                'capabilities': {'workspace': {'applyEdit': False, 'configuration': True},
                                 'window': {'workDoneProgress': False},
                                 'textDocument': {'publishDiagnostics': {}, 'diagnostic': {},
                                                  'definition': {}, 'references': {}, 'synchronization': {}}},
            }, timeout_sec=45.0)
            if reply and 'error' not in reply:
                self._capabilities = (reply.get('result') or {}).get('capabilities') or {}
                self.notify('initialized', {})
                return True, ''
            last_error = 'LSP_INITIALIZE_FAILED: %s' % (reply or 'no reply')
            detail = ''.join(self.handles.stderr_lines)[:300].replace(chr(10), ' ')
            if detail:
                last_error += ' | ' + detail
            # Never try another allowlisted executable while the previous
            # language-server group is uncertain.  Continuing here would
            # publish a replacement daemon while an initialize-failed server
            # remained detached from it.
            if not self.stop():
                return False, 'LSP_STOP_UNCONFIRMED'
        return False, last_error or 'LSP_SERVER_UNAVAILABLE'
    def handshake(self):
        reply = self.request('initialize', {
            'processId': os.getpid(),
            'rootUri': self.root_uri,
            'capabilities': {'workspace': {'applyEdit': False}},
        }, timeout_sec=15.0)
        if not reply or 'result' not in reply:
            return False
        self.notify('initialized', {})
        return True

    def notify(self, method, params):
        with self._io_lock:
            self._write({'jsonrpc': '2.0', 'method': method, 'params': params})

    def document_notification(self, method, params):
        # Notifications share the same actual-source synchronization as queries;
        # caller-supplied replacement text cannot bypass mirror ownership.
        if method not in ('textDocument/didOpen', 'textDocument/didChange', 'textDocument/didSave', 'textDocument/didClose'):
            return {'error': 'LSP_NOTIFICATION_UNSUPPORTED'}
        with self._io_lock:
            uri = (params.get('textDocument') or {}).get('uri', '')
            try:
                self._synchronize_document(uri)
                if method in ('textDocument/didSave', 'textDocument/didClose'):
                    self.notify(method, {'textDocument': {'uri': uri}})
                if method == 'textDocument/didClose':
                    self._documents.pop(document_key(uri), None)
                    with self._reply_condition:
                        self._diagnostics.pop(document_key(uri), None)
            except (OSError, ValueError, UnicodeError) as error:
                return {'error': str(error)}
            return {'ok': True}

    def _read_messages(self):
        """One stdio reader also handles diagnostics published while idle."""
        try:
            while not self._cancel_event.is_set():
                headers = {}
                while True:
                    line = self.process.stdout.readline(4097)
                    if not line or len(line) > 4096:
                        raise ValueError('LSP_PROTOCOL_INVALID')
                    if line in (b'\r\n', b'\n'):
                        break
                    key, value = line.decode('ascii').split(':', 1)
                    headers[key.strip().lower()] = value.strip()
                size = int(headers.get('content-length', '-1'))
                if not 0 <= size <= MAX_FRAME_BYTES:
                    raise ValueError('LSP_FRAME_LIMIT')
                body = self.process.stdout.read(size)
                if len(body) != size:
                    raise ValueError('LSP_PROTOCOL_INVALID')
                message = json.loads(body.decode('utf-8'))
                method = message.get('method')
                if method == 'textDocument/publishDiagnostics':
                    params = message.get('params') or {}
                    with self._reply_condition:
                        self._diagnostics[document_key(params.get('uri', ''))] = params
                        self._reply_condition.notify_all()
                elif method and 'id' in message:
                    # Respond to normal server discovery requests without permitting edits.
                    params = message.get('params') or {}
                    if method == 'workspace/applyEdit':
                        result = {'applied': False, 'failureReason': 'read-only code intelligence'}
                    elif method == 'workspace/configuration':
                        result = [{} for _ in params.get('items', [])]
                    elif method == 'workspace/workspaceFolders':
                        result = [{'uri': self.root_uri, 'name': 'main'}]
                    else:
                        result = None
                    self._write({'jsonrpc': '2.0', 'id': message['id'], 'result': result})
                elif 'id' in message:
                    with self._reply_condition:
                        # A timed-out request cannot accumulate unbounded stale replies.
                        if len(self._responses) > 32:
                            self._responses.clear()
                        self._responses[message['id']] = message
                        self._reply_condition.notify_all()
        except (OSError, ValueError, TypeError, UnicodeError) as error:
            with self._reply_condition:
                self._reader_error = str(error)
                self._reply_condition.notify_all()

    def _synchronize_document(self, uri):
        parsed = urlparse(uri)
        if parsed.scheme != 'file' or parsed.netloc not in ('', 'localhost'):
            raise ValueError('LSP_PATH_REJECTED')
        path = os.path.realpath(file_uri_path(parsed.path))
        if not path.startswith(self.source_root + os.sep):
            raise ValueError('LSP_PATH_REJECTED')
        with open(path, 'rb') as source:
            raw = source.read(MAX_FRAME_BYTES + 1)
        if len(raw) > MAX_FRAME_BYTES:
            raise ValueError('LSP_FRAME_LIMIT')
        text = raw.decode('utf-8')
        key = document_key(uri)
        previous = self._documents.get(key)
        if previous and previous[1] == text:
            return previous[0]
        version = previous[0] + 1 if previous else 1
        with self._reply_condition:
            self._diagnostics.pop(document_key(uri), None)
        if previous:
            self.notify('textDocument/didChange', {'textDocument': {'uri': uri, 'version': version},
                                                  'contentChanges': [{'text': text}]})
        else:
            self.notify('textDocument/didOpen', {'textDocument': {'uri': uri, 'version': version,
                        'languageId': self.server_id, 'text': text}})
        self._documents[key] = (version, text)
        return version

    def request(self, method, params, timeout_sec, cancel_event=None, _reference_redirect=False):
        # Serialize a complete stdio exchange. The daemon socket can receive
        # concurrent Android requests, but one reader must not consume another
        # request's response and turn a bounded call into a false timeout.
        with self._io_lock:
            cancellation = cancel_event or self._cancel_event
            if cancellation.is_set():
                return {'error': 'LSP_CANCELLED'}
            if method.startswith('textDocument/'):
                uri = (params.get('textDocument') or {}).get('uri', '')
                try:
                    version = self._synchronize_document(uri)
                except (OSError, ValueError, UnicodeError) as error:
                    return {'error': str(error)}
                if method == 'textDocument/diagnostic' and not self._capabilities.get('diagnosticProvider'):
                    deadline = time.monotonic() + min(timeout_sec, 5.0)
                    with self._reply_condition:
                        while not cancellation.is_set():
                            result = self._diagnostics.get(document_key(uri))
                            if result is not None and result.get('version', version) >= version:
                                return {'result': {'kind': 'full', 'items': result.get('diagnostics', [])}}
                            remaining = deadline - time.monotonic()
                            if remaining <= 0 or self._reader_error:
                                return {'error': 'LSP_DIAGNOSTICS_NOT_READY'}
                            self._reply_condition.wait(min(remaining, 0.05))
                    return {'error': 'LSP_CANCELLED'}
            self.request_id += 1
            token = self.request_id
            if not self._write({'jsonrpc': '2.0', 'id': token, 'method': method, 'params': params}):
                return {'error': 'LSP_UNAVAILABLE'}
            deadline = time.time() + max(0.001, timeout_sec)
            while True:
                if cancellation.is_set():
                    return {'error': 'LSP_CANCELLED'}
                remaining = deadline - time.time()
                if remaining <= 0:
                    return {'error': 'LSP_TIMEOUT'}
                if self.process is None or self.process.poll() is not None:
                    return {'error': 'LSP_CRASHED'}
                with self._reply_condition:
                    message = self._responses.pop(token, None)
                    if message is not None:
                        # fwcd 1.3.13 resolves references at declarations but may return
                        # [] at a call site. Resolve its own definition first, then
                        # ask the same server; never substitute the lexical index.
                        if (self.server_id == 'kotlin' and method == 'textDocument/references'
                                and message.get('result') == [] and not _reference_redirect):
                            remaining = deadline - time.time()
                            definition = self.request('textDocument/definition', params, remaining, cancellation)
                            locations = definition.get('result') or []
                            if isinstance(locations, dict):
                                locations = [locations]
                            if locations and deadline > time.time():
                                target = locations[0]
                                redirected = dict(params, textDocument={'uri': target.get('uri', '')},
                                                  position=(target.get('range') or {}).get('start', {}))
                                return self.request(method, redirected, deadline - time.time(), cancellation, True)
                        return message
                    if self._reader_error:
                        return {'error': 'LSP_PROTOCOL_INVALID', 'detail': self._reader_error}
                    self._reply_condition.wait(min(remaining, 0.05))

    def _write(self, payload):
        if self.process is None or self.process.poll() is not None:
            return False
        body = json.dumps(payload).encode('utf-8')
        if len(body) > MAX_FRAME_BYTES:
            return False
        header = ('Content-Length: %d\r\n\r\n' % len(body)).encode('ascii')
        try:
            with self._write_lock:
                self.process.stdin.write(header + body)
                self.process.stdin.flush()
            return True
        except (BrokenPipeError, OSError):
            return False

    def stop(self):
        """Stop the language-server group and prove the group is gone."""
        # Set cancellation before taking the stop lock so a request blocked in
        # read_frame can leave its I/O lock while this barrier waits.
        self._cancel_event.set()
        with self._stop_lock:
            process = self.process
            if process is None:
                return True
            group_id = self.process_group_id or process.pid
            try:
                if hasattr(os, 'killpg'):
                    os.killpg(group_id, signal.SIGTERM)
                else:
                    process.terminate()
            except (OSError, ValueError):
                # The process may already have exited; the final barrier below
                # decides whether that is a confirmed stop.
                pass
            deadline = time.time() + 3.0
            while (process.poll() is None or self._group_alive(group_id)) and time.time() < deadline:
                time.sleep(0.05)
            if process.poll() is None or self._group_alive(group_id):
                try:
                    if hasattr(os, 'killpg'):
                        os.killpg(group_id, signal.SIGKILL)
                    else:
                        process.kill()
                except (OSError, ValueError):
                    pass
                try:
                    process.wait(timeout=3.0)
                except subprocess.TimeoutExpired:
                    pass
            final_deadline = time.time() + 3.0
            while (process.poll() is None or self._group_alive(group_id)) and time.time() < final_deadline:
                time.sleep(0.05)
            stopped = process.poll() is not None and not self._group_alive(group_id)
            if stopped:
                for stream in (process.stdin, process.stdout, process.stderr):
                    try:
                        stream.close()
                    except OSError:
                        pass
                for thread in (self._reader_thread, self._stderr_thread):
                    if thread is not None and thread is not threading.current_thread():
                        thread.join(timeout=1.0)
                if self._storage:
                    shutil.rmtree(self._storage)
                    self._storage = None
                self.process = None
                self.process_group_id = None
            return stopped

    @staticmethod
    def _group_alive(group_id):
        if not hasattr(os, 'killpg'):
            return False
        try:
            os.killpg(group_id, 0)
        except (OSError, ValueError):
            return False
        # killpg(0) can still succeed while only zombie entries remain.  A
        # STOPPED acknowledgement is a process-group barrier, not merely a
        # leader-PID check, so inspect the group state where /proc is present.
        try:
            for entry in os.listdir('/proc'):
                if not entry.isdigit():
                    continue
                try:
                    with open('/proc/%s/stat' % entry, encoding='ascii') as handle:
                        raw = handle.read()
                    tail = raw[raw.rfind(')') + 2:].split()
                    if len(tail) >= 3 and int(tail[2]) == int(group_id) and tail[0] != 'Z':
                        return True
                except (OSError, ValueError, IndexError):
                    continue
            return False
        except OSError:
            return True


def shutil_which(name):
    for directory in os.environ.get('PATH', '').split(os.pathsep):
        candidate = os.path.join(directory, name)
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    return None


def file_uri_path(path):
    path = unquote(path or '')
    # Standard Windows file URIs have /C:/..., unlike POSIX guest paths.
    if os.name == 'nt' and len(path) >= 3 and path[0] == '/' and path[2] == ':':
        path = path[1:]
    return path


def document_key(uri):
    """Servers may encode URI characters or change drive-letter case."""
    parsed = urlparse(uri)
    return os.path.normcase(os.path.realpath(file_uri_path(parsed.path)))


def root_path_from_uri(root_uri):
    """Return a validated physical execution root for a file:// URI."""
    try:
        parsed = urlparse(root_uri)
        if parsed.scheme.lower() != 'file' or parsed.netloc not in ('', 'localhost'):
            return None
        path = file_uri_path(parsed.path)
        if not path or '\x00' in path or not os.path.isabs(path):
            return None
        normalized = os.path.realpath(path)
        if not os.path.isdir(normalized):
            return None
        return normalized
    except (TypeError, ValueError, OSError):
        return None


def read_frame(stream, timeout_sec, cancel_event=None):
    """Read one Content-Length frame under one deadline and cancellation token."""
    handle = stream
    deadline = time.time() + timeout_sec
    length = -1
    line = bytearray()

    while True:
        if cancel_event is not None and cancel_event.is_set():
            return None
        remaining = deadline - time.time()
        if remaining <= 0:
            return b''
        ready, _, _ = select.select([handle], [], [], min(remaining, 0.05))
        if not ready:
            continue
        if cancel_event is not None and cancel_event.is_set():
            return None
        # os.read is intentional: BufferedReader.read can still block after
        # select while trying to fill its internal buffer.
        char = os.read(handle.fileno(), 1)
        if not char:
            return b''
        if char == b'\n':
            text = bytes(line).decode('ascii', errors='replace').strip()
            line = bytearray()
            if not text:
                break
            if text.lower().startswith('content-length:'):
                try:
                    length = int(text.split(':', 1)[1].strip())
                except ValueError:
                    return b''
        else:
            line.extend(char)
            if len(line) > 4096:
                return b''

    if length < 0 or length > MAX_FRAME_BYTES:
        return b''

    body = bytearray()
    while len(body) < length:
        if cancel_event is not None and cancel_event.is_set():
            return None
        remaining = deadline - time.time()
        if remaining <= 0:
            return b''
        ready, _, _ = select.select([handle], [], [], min(remaining, 0.05))
        if not ready:
            continue
        if cancel_event is not None and cancel_event.is_set():
            return None
        chunk = os.read(handle.fileno(), min(4096, length - len(body)))
        if not chunk:
            return b''
        body.extend(chunk)
    return bytes(body)


def serve(socket_path, root_uri, server_id, session_key, tcp_secret=None, ready=None, source_root=None):
    if socket_path and os.path.exists(socket_path):
        os.remove(socket_path)
    server = LanguageServer(server_id, root_uri, source_root)
    listener = None
    stopping = threading.Event()
    workers = set()
    workers_lock = threading.Lock()

    def handle_termination(_signum, _frame):
        # Route signals through the same cancellation and process-group barrier
        # used by an explicit stop/abort connection.
        stopping.set()
        server.stop()

    signal.signal(signal.SIGTERM, handle_termination)
    signal.signal(signal.SIGINT, handle_termination)
    try:
        started, error = server.start()
        if not started:
            print('LSP_START_FAILED %s' % error, file=sys.stderr, flush=True)
            return 2
        listener = socket.socket(socket.AF_INET if tcp_secret else socket.AF_UNIX, socket.SOCK_STREAM)
        listener.bind(('127.0.0.1', 0) if tcp_secret else socket_path)
        listener.listen(4)
        listener.settimeout(0.2)
        if tcp_secret:
            if ready:
                ready({'ok': True, 'port': listener.getsockname()[1], 'rootUri': root_uri})
        else:
            os.chmod(socket_path, 0o600)

        def handle_connection(connection):
            current = threading.current_thread()
            try:
                # Parsing is bounded independently of a language-server
                # request. A stop command has a worker of its own and can
                # therefore cancel another worker blocked in read_frame.
                connection.settimeout(5.0)
                buffer = b''
                while b'\n' not in buffer:
                    chunk = connection.recv(65536)
                    if not chunk:
                        break
                    buffer += chunk
                    if len(buffer) > MAX_FRAME_BYTES:
                        break
                if b'\n' not in buffer or len(buffer.split(b'\n', 1)[0]) > MAX_FRAME_BYTES:
                    return
                try:
                    request = json.loads(buffer.split(b'\n', 1)[0].decode('utf-8', errors='replace'))
                except ValueError:
                    connection.sendall(b'{"error":"LSP_PROTOCOL_INVALID"}\n')
                    return
                if tcp_secret and not hmac.compare_digest(str(request.get('secret', '')), tcp_secret):
                    connection.sendall(b'{"error":"LSP_AUTHORITY_REJECTED"}\n')
                    return

                action = request.get('action')
                if action == 'ping':
                    if not stopping.is_set():
                        connection.sendall(b'pong\n')
                elif action == 'stop':
                    stopping.set()
                    if server.stop():
                        connection.sendall(b'stopped\n')
                    else:
                        connection.sendall(b'{"error":"LSP_STOP_UNCONFIRMED"}\n')
                elif action == 'request':
                    timeout = max(0.001, min(float(request.get('timeoutSec', 10.0)), 120.0))
                    if stopping.is_set():
                        reply = {'error': 'LSP_CANCELLED'}
                    elif server.process is None or server.process.poll() is not None:
                        reply = {'error': 'LSP_CRASHED'}
                    else:
                        reply = server.request(request.get('method', ''),
                                               request.get('params', {}), timeout, stopping)
                    connection.sendall((json.dumps(reply) + '\n').encode('utf-8'))
                elif action == 'notify':
                    reply = {'error': 'LSP_CANCELLED'} if stopping.is_set() else server.document_notification(
                        request.get('method', ''), request.get('params', {}))
                    connection.sendall((json.dumps(reply) + '\n').encode('utf-8'))
                else:
                    connection.sendall(b'{"error":"LSP_ACTION_UNKNOWN"}\n')
            except (OSError, ValueError, TypeError):
                pass
            finally:
                connection.close()
                with workers_lock:
                    workers.discard(current)

        while not stopping.is_set():
            try:
                connection, _ = listener.accept()
            except socket.timeout:
                continue
            except OSError:
                break
            worker = threading.Thread(target=handle_connection, args=(connection,), daemon=True)
            with workers_lock:
                workers.add(worker)
            worker.start()
    except BaseException:
        traceback.print_exc(file=sys.stderr)
        return 1
    finally:
        stopping.set()
        server.stop()
        if listener is not None:
            listener.close()
        # Request workers observe the same cancellation token from
        # LanguageServer.stop(). Join briefly before the daemon exits.
        deadline = time.time() + 5.0
        while time.time() < deadline:
            with workers_lock:
                active = list(workers)
            if not active:
                break
            for worker in active:
                worker.join(timeout=max(0.0, min(0.1, deadline - time.time())))
        if socket_path:
            try:
                os.remove(socket_path)
            except OSError:
                pass
    return 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--socket')
    parser.add_argument('--secret')
    parser.add_argument('--control-url')
    parser.add_argument('--source-root')
    parser.add_argument('--root-uri', required=True)
    parser.add_argument('--server', required=True)
    parser.add_argument('--session', required=True)
    arguments = parser.parse_args()
    if not arguments.socket and not (arguments.secret and arguments.control_url):
        parser.error('socket or supervised control channel required')
    def publish(result):
        url = urlparse(arguments.control_url or '')
        if url.scheme != 'http' or url.hostname != '127.0.0.1':
            raise ValueError('LSP_CONTROL_URL_INVALID')
        request = urllib.request.Request(arguments.control_url + '/result',
                    data=json.dumps(result).encode('utf-8'), method='POST')
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        with opener.open(request, timeout=10) as response:
            response.read()
    sys.exit(serve(arguments.socket, arguments.root_uri, arguments.server, arguments.session,
                   arguments.secret, publish if arguments.control_url else None, arguments.source_root))


if __name__ == '__main__':
    main()
