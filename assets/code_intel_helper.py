KEYWORDS = {
    'class', 'interface', 'fun', 'val', 'var', 'def', 'package', 'import', 'return',
    'if', 'else', 'for', 'while', 'do', 'switch', 'case', 'break', 'continue',
    'public', 'private', 'protected', 'static', 'final', 'abstract', 'const', 'let',
    'null', 'true', 'false', 'new', 'this', 'super', 'try', 'catch', 'finally',
    'throw', 'object', 'typealias', 'enum', 'record', 'async', 'await', 'from',
    'as', 'in', 'is', 'not', 'and', 'or', 'with', 'pass', 'raise', 'yield'
}


def strip_comment_and_strings(line, is_python):
    out = []
    in_string = False
    quote = ''
    index = 0
    while index < len(line):
        char = line[index]
        if in_string:
            if char == quote and (index == 0 or line[index - 1] != '\\'):
                in_string = False
            out.append(' ')
        else:
            if not is_python and char == '/' and index + 1 < len(line) and line[index + 1] == '/':
                break
            if is_python and char == '#':
                break
            if char in ('"', "'") or (not is_python and char == '`'):
                in_string = True
                quote = char
                out.append(' ')
            else:
                out.append(char)
        index += 1
    return ''.join(out)


def language_of(path):
    lower = path.lower()
    if lower.endswith('.kt') or lower.endswith('.kts'):
        return 'kotlin'
    if lower.endswith('.java'):
        return 'java'
    if lower.endswith('.py'):
        return 'python'
    if lower.endswith('.ts') or lower.endswith('.tsx'):
        return 'typescript'
    if lower.endswith('.js') or lower.endswith('.jsx') or lower.endswith('.mjs'):
        return 'javascript'
    return 'unknown'


def parse_source(rel_path, text):
    language = language_of(rel_path)
    is_python = language == 'python'
    symbols = []
    references = []
    package = ''
    container = None

    class_re = re.compile(r'\b(class|interface|object|enum)\s+([A-Za-z0-9_]+)')
    fun_re = re.compile(r'\b(?:fun|def|function)\s+([A-Za-z0-9_]+)\s*\(')
    field_re = re.compile(r'\b(val|var|const|let)\s+([A-Za-z0-9_]+)\s*[:=]')
    ident_re = re.compile(r'\b([A-Za-z_][A-Za-z0-9_]{1,})\b')
    package_re = re.compile(r'^\s*package\s+([A-Za-z0-9_.]+)')

    for number, raw in enumerate(text.splitlines(), start=1):
        line = strip_comment_and_strings(raw, is_python)
        match = package_re.match(line)
        if match:
            package = match.group(1)

        for match in class_re.finditer(line):
            name = match.group(2)
            kind = 'interface' if 'interface' in match.group(1) else (
                'enum' if 'enum' in match.group(1) else 'class')
            column = match.start(2) + 1
            container = name
            qualified = (package + '.' + name) if package else name
            symbols.append((name, qualified, kind, number, column, column + len(name)))
        for match in fun_re.finditer(line):
            name = match.group(1)
            column = match.start(1) + 1
            qualified = (container + '.' + name) if container else name
            symbols.append((name, qualified, 'method' if container else 'function',
                            number, column, column + len(name)))
        for match in field_re.finditer(line):
            name = match.group(2)
            column = match.start(2) + 1
            qualified = (container + '.' + name) if container else name
            symbols.append((name, qualified, 'field' if container else 'variable',
                            number, column, column + len(name)))
        for match in ident_re.finditer(line):
            name = match.group(1)
            if name in KEYWORDS:
                continue
            column = match.start(1) + 1
            references.append((name, number, column, column + len(name)))

    return symbols[:MAX_SYMBOLS_PER_FILE], references[:MAX_REFERENCES_PER_FILE], language


def build_snapshot(project_root, db_path, rel_paths):
    if os.path.exists(db_path):
        os.remove(db_path)
    connection = sqlite3.connect(db_path)
    cursor = connection.cursor()
    cursor.execute('CREATE TABLE files (id TEXT PRIMARY KEY, path TEXT, sha256 TEXT, language TEXT)')
    cursor.execute('CREATE TABLE symbols (file_id TEXT, name TEXT, qualified TEXT, kind TEXT,'
                   ' start_line INTEGER, start_col INTEGER, end_line INTEGER, end_col INTEGER)')
    cursor.execute('CREATE TABLE refs (file_id TEXT, name TEXT, start_line INTEGER, start_col INTEGER,'
                   ' end_line INTEGER, end_col INTEGER)')

    indexed_files = 0
    indexed_symbols = 0
    for rel in rel_paths:
        full = os.path.join(project_root, rel)
        if not os.path.isfile(full):
            continue
        try:
            if os.path.getsize(full) > MAX_FILE_BYTES:
                continue
            with open(full, 'rb') as handle:
                data = handle.read()
            text = data.decode('utf-8', errors='replace')
        except OSError:
            continue
        import hashlib
        file_id = hashlib.sha1(rel.encode('utf-8')).hexdigest()
        symbols, references, language = parse_source(rel, text)
        cursor.execute('INSERT OR REPLACE INTO files VALUES (?, ?, ?, ?)',
                       (file_id, rel, hashlib.sha256(data).hexdigest(), language))
        for symbol in symbols:
            cursor.execute('INSERT INTO symbols VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
                           (file_id, symbol[0], symbol[1], symbol[2],
                            symbol[3], symbol[4], symbol[3], symbol[5]))
        for reference in references:
            cursor.execute('INSERT INTO refs VALUES (?, ?, ?, ?, ?, ?)',
                           (file_id, reference[0], reference[1], reference[2],
                            reference[1], reference[3]))
        indexed_files += 1
        indexed_symbols += len(symbols)
    connection.commit()
    connection.close()
    return {'files': indexed_files, 'symbols': indexed_symbols}


