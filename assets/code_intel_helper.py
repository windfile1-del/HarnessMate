#!/usr/bin/env python3
"""Vega Safe Phase 5 - trusted Code Intelligence helper.

Runs inside the Termux execution workspace, started by the same trusted bridge
P3 already uses (assets/mirror_helper.py bootstrap): the APK asset is streamed
over an internally generated loopback URL and piped into python3. The model
never supplies this script, a path, an executable or argv.

Contract:
  argv[1] = loopback control URL (validated, generated by the app)
  "control" route -> {protocolVersion, operation, workspaceId, args, ...}
  result POSTed back to the "/result" route.

This helper holds NO long-lived workspace lock: the language server daemon is
spawned detached in its own session, so P3 shell/build/test are never blocked
by an idle LSP. Ordinary operations may take the short P3 flock they need.

Nothing here reads or writes the SAF canonical tree. Everything happens under
the persistent execution mirror root:
  <root>/project          <- the code the daemon indexes
  <root>/.vega/code-intel <- daemon scripts, sockets, logs, index snapshots
"""

