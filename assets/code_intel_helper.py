def code_intel_dir(root):
    target = os.path.join(root, '.vega', 'code-intel')
    os.makedirs(target, exist_ok=True)
    return target


def session_dir(root, session_key):
    if not SESSION_KEY_RE.fullmatch(session_key):
        raise ValueError('LSP_SESSION_KEY_INVALID')
    target = os.path.join(code_intel_dir(root), 'lsp', session_key)
    os.makedirs(target, exist_ok=True)
    return target


def cancel_path(directory):
    return os.path.join(directory, 'cancel.requested')


def claim_path(directory):
    """Durable owner claim held from start dispatch through group teardown."""
    return os.path.join(directory, 'attempt.claim')


def read_cancel(directory):
    try:
        with open(cancel_path(directory), encoding='utf-8') as handle:
            value = json.load(handle)
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return None


def write_cancel(directory, attempt_id, identity):
    if attempt_id and not ATTEMPT_ID_RE.fullmatch(str(attempt_id)):
        raise ValueError('LSP_ATTEMPT_ID_INVALID')
    target = cancel_path(directory)
    temporary = target + '.tmp.%s' % os.getpid()
    with open(temporary, 'w', encoding='utf-8') as handle:
        json.dump({'attemptId': str(attempt_id or ''), 'identity': identity or {},
                   'requestedAt': time.time()}, handle)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, target)


def remove_cancel(directory):
    try:
        os.remove(cancel_path(directory))
    except OSError:
        pass


def cancel_matches(directory, attempt_id):
    marker = read_cancel(directory)
    if marker is None:
        return False
    marker_attempt = str(marker.get('attemptId') or '')
    # Empty attempt ids are retained for compatibility with older callers;
    # production Kotlin always supplies a fresh 32-hex attempt id.
    return marker_attempt == str(attempt_id or '')


def read_claim(directory):
    try:
        with open(claim_path(directory), encoding='utf-8') as handle:
            value = json.load(handle)
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError, TypeError):
        return None


def claim_is_live(claim):
    """Return true while either the dispatch owner or detached daemon lives."""
    if not isinstance(claim, dict):
        return False
    return any(process_alive(claim.get(key)) for key in ('ownerPid', 'daemonPid'))


def write_claim(directory, attempt_id, identity, daemon_pid=0, phase='starting'):
    """Atomically create the first-writer-wins attempt owner claim."""
    if not ATTEMPT_ID_RE.fullmatch(str(attempt_id or '')):
        raise ValueError('LSP_ATTEMPT_ID_REQUIRED')
    target = claim_path(directory)
    payload = {'attemptId': str(attempt_id), 'identity': identity or {},
               'ownerPid': os.getpid(), 'daemonPid': int(daemon_pid or 0),
               'phase': phase, 'createdAt': time.time()}
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    descriptor = os.open(target, flags, 0o600)
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8') as handle:
            descriptor = None
            json.dump(payload, handle)
            handle.flush()
            os.fsync(handle.fileno())
    finally:
        if descriptor is not None:
            os.close(descriptor)


def update_claim(directory, attempt_id, identity=None, daemon_pid=None, phase=None):
    """Update only our exact claim, preserving atomic publication semantics."""
    current = read_claim(directory)
    if not current or str(current.get('attemptId') or '') != str(attempt_id):
        return False
    if identity is not None and current.get('identity') != identity:
        return False
    payload = dict(current)
    if identity is not None:
        payload['identity'] = identity
    if daemon_pid is not None:
        payload['daemonPid'] = int(daemon_pid or 0)
    if phase is not None:
        payload['phase'] = phase
    payload['updatedAt'] = time.time()
    target = claim_path(directory)
    temporary = target + '.tmp.%s' % os.getpid()
    with open(temporary, 'w', encoding='utf-8') as handle:
        json.dump(payload, handle)
        handle.flush()
        os.fsync(handle.fileno())
    # Re-check before replace.  A replacement owner must never be overwritten
    # by a late update from an older attempt.
    latest = read_claim(directory)
    if not latest or str(latest.get('attemptId') or '') != str(attempt_id):
        try:
            os.remove(temporary)
        except OSError:
            pass
        return False
    os.replace(temporary, target)
    return True


def remove_claim(directory, attempt_id):
    """Remove only an exact owner claim; stale/foreign claims remain intact."""
    current = read_claim(directory)
    if not current or str(current.get('attemptId') or '') != str(attempt_id):
        return False
    try:
        os.remove(claim_path(directory))
    except OSError:
        return False
    return True


def _proc_snapshot():
    """Return {pid: (ppid, pgid, state)} on Termux/Linux, or an empty map."""
    if os.name == 'nt':
        return {}
    snapshot = {}
    try:
        entries = os.listdir('/proc')
    except OSError:
        return snapshot
    for entry in entries:
        if not entry.isdigit():
            continue
        try:
            with open('/proc/%s/stat' % entry, encoding='ascii') as handle:
                raw = handle.read()
            # comm may contain spaces; the final ')' is the reliable delimiter.
            tail = raw[raw.rfind(')') + 2:].split()
            if len(tail) < 3:
                continue
            snapshot[int(entry)] = (int(tail[1]), int(tail[2]), tail[0])
        except (OSError, ValueError, IndexError):
            continue
    return snapshot


def _process_tree(root_pid):
    """Capture all descendants and process groups before a parent can exit."""
    try:
        root = int(root_pid)
    except (TypeError, ValueError):
        return set(), set()
    snapshot = _proc_snapshot()
    if not snapshot:
        try:
            group = os.getpgid(root) if hasattr(os, 'getpgid') else root
        except (OSError, ValueError):
            group = root
        return ({root} if process_alive(root) else set()), {group}
    pids = {root} if root in snapshot else set()
    changed = True
    while changed:
        changed = False
        for pid, (ppid, _pgid, _state) in snapshot.items():
            if pid not in pids and ppid in pids:
                pids.add(pid)
                changed = True
    groups = {snapshot[pid][1] for pid in pids if pid in snapshot}
    return pids, groups


def _group_alive(group_id):
    if not group_id or not hasattr(os, 'killpg'):
        return False
    try:
        os.killpg(int(group_id), 0)
    except (OSError, ValueError, TypeError):
        return False
    snapshot = _proc_snapshot()
    if snapshot:
        return any(info[1] == int(group_id) and info[2] != 'Z'
                   for info in snapshot.values())
    return True


def process_alive(pid):
    if not pid:
        return False
    try:
        numeric = int(pid)
        os.kill(numeric, 0)
        # A detached child can briefly remain a zombie after its group exits;
        # treating that unreapable entry as live would make every confirmed
        # stop time out forever on Termux's process supervisor.
        proc_stat = '/proc/%d/stat' % numeric
        try:
            with open(proc_stat, encoding='ascii') as handle:
                raw = handle.read()
            tail = raw[raw.rfind(')') + 2:].split()
            if tail and tail[0] == 'Z':
                return False
        except OSError:
            pass
        return True
    except (OSError, ValueError, TypeError):
        return False


def _signal_groups(groups, signum):
    """Signal captured groups, never the helper's own process group."""
    own_group = os.getpgrp() if hasattr(os, 'getpgrp') else None
    for group_id in sorted({int(g) for g in groups if g}):
        if own_group is not None and group_id == own_group:
            continue
        try:
            if hasattr(os, 'killpg'):
                os.killpg(group_id, signum)
            else:
                os.kill(group_id, signum)
        except (OSError, ValueError, TypeError):
            pass


def _targets_gone(pids, groups):
    return (not any(process_alive(pid) for pid in pids) and
            not any(_group_alive(group_id) for group_id in groups))


def terminate_process_group(pid, initial_tree=None):
    """Terminate daemon and every descendant process group with a hard barrier.

    The daemon and language server intentionally use separate sessions.  A
    daemon-only kill therefore is not sufficient: capture the complete process
    tree before signalling, signal child groups first, and verify every captured
    PID/group is gone after both graceful and forced phases.  The captured tree
    is accepted from stop_daemon so a daemon that exits while sending ``stopped``
    cannot erase the only evidence of its independent language-server group.
    """
    if not pid:
        return True
    pids, groups = initial_tree or (set(), set())
    fresh_pids, fresh_groups = _process_tree(pid)
    pids = set(pids) | fresh_pids
    groups = set(groups) | fresh_groups
    if not pids and not groups:
        return not process_alive(pid)

    # Give the daemon's signal handler a chance, but explicitly signal all
    # descendant groups as well.  This closes the daemon-group/LS-group gap.
    _signal_groups(groups, signal.SIGTERM)
    deadline = time.time() + LSP_STOP_TIMEOUT_SEC + 2.0
    while time.time() < deadline:
        current_pids, current_groups = _process_tree(pid)
        pids.update(current_pids)
        groups.update(current_groups)
        if _targets_gone(pids, groups):
            return True
        time.sleep(0.05)

    # Re-scan immediately before SIGKILL to catch a language server spawned
    # during the startup/abort race, then force-kill every known group.
    current_pids, current_groups = _process_tree(pid)
    pids.update(current_pids)
    groups.update(current_groups)
    _signal_groups(groups, signal.SIGKILL)
    deadline = time.time() + 5.0
    while time.time() < deadline:
        current_pids, current_groups = _process_tree(pid)
        pids.update(current_pids)
        groups.update(current_groups)
        if _targets_gone(pids, groups):
            return True
        time.sleep(0.05)
    return _targets_gone(pids, groups)


def socket_alive(path):
    if not os.path.exists(path):
        return False
    probe = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    probe.settimeout(1.0)
    try:
        probe.connect(path)
        probe.sendall(b'{"action":"ping"}\n')
        data = probe.recv(4096)
        return b'pong' in data
    except OSError:
        return False
    finally:
        probe.close()


def start_daemon(root, session_key, daemon_source, server_id, token, language,
                 identity=None, attempt_id=''):
    directory = session_dir(root, session_key)
    daemon_path = os.path.join(code_intel_dir(root), 'lsp_daemon.py')
    sock_path = os.path.join(directory, 'server.sock')
    state_path = os.path.join(directory, 'state.json')
    log_path = os.path.join(directory, 'stderr.log')
    root_uri = 'file://' + os.path.join(root, 'project')

    if not attempt_id:
        return {'ok': False, 'error': 'LSP_ATTEMPT_ID_REQUIRED'}
    if not ATTEMPT_ID_RE.fullmatch(str(attempt_id)):
        return {'ok': False, 'error': 'LSP_ATTEMPT_ID_INVALID'}

    # Claim the attempt before any marker cleanup or Popen.  This closes the
    # pre-publication window where A had started a daemon but had not yet
    # published state.json/server.sock and B could otherwise erase A's marker
    # and take ownership.  A claim is durable and first-writer-wins.
    existing_claim = read_claim(directory)
    if existing_claim is not None:
        existing_attempt = str(existing_claim.get('attemptId') or '')
        if existing_attempt == str(attempt_id):
            if os.path.exists(sock_path) or os.path.exists(state_path):
                return {'ok': False, 'error': 'LSP_ATTEMPT_ALREADY_PUBLISHED'}
            return {'ok': False, 'error': 'LSP_ATTEMPT_ALREADY_RUNNING'}
        if claim_is_live(existing_claim):
            return {'ok': False, 'error': 'LSP_ATTEMPT_OWNERSHIP_MISMATCH'}
        # Recovery is permitted only after both the dispatch owner and daemon
        # recorded in the stale claim are confirmed dead.
        remove_claim(directory, existing_attempt)

    # Never replace a live or uncertain session.  In particular, do not unlink
    # a socket after an unconfirmed stop: doing so would publish a second
    # daemon while the first language-server group is still running.  The
    # attempt id is part of the durable owner identity: a late start from an
    # older attempt must fail closed instead of stopping/replacing the live
    # newer attempt.
    if os.path.exists(sock_path) or os.path.exists(state_path):
        if not os.path.exists(state_path):
            return {'ok': False, 'error': 'LSP_STATE_MISSING'}
        try:
            with open(state_path, encoding='utf-8') as handle:
                existing = json.load(handle)
        except (OSError, ValueError, TypeError):
            return {'ok': False, 'error': 'LSP_STATE_INVALID'}
        existing_attempt = str(existing.get('attemptId') or '')
        if existing_attempt != str(attempt_id or ''):
            return {'ok': False, 'error': 'LSP_ATTEMPT_OWNERSHIP_MISMATCH'}
        return {'ok': False, 'error': 'LSP_ATTEMPT_ALREADY_PUBLISHED'}

    try:
        write_claim(directory, attempt_id, identity or {})
    except FileExistsError:
        # A concurrent starter won the O_EXCL race.  Re-read its durable
        # identity and fail closed; never delete its marker or claim here.
        winner = read_claim(directory)
        if winner and str(winner.get('attemptId') or '') == str(attempt_id):
            return {'ok': False, 'error': 'LSP_ATTEMPT_ALREADY_RUNNING'}
        return {'ok': False, 'error': 'LSP_ATTEMPT_OWNERSHIP_MISMATCH'}
    except (OSError, ValueError) as error:
        return {'ok': False, 'error': '%s: %s' % (error.__class__.__name__, error)}

    claim_owned = True

    def finish(result, keep_claim=False):
        if claim_owned and not keep_claim:
            remove_claim(directory, attempt_id)
        return result

    # A cancellation can arrive while ACTION_RUN_COMMAND is still starting
    # this helper.  Consume only an exact marker.  A stale marker from an older
    # attempt is safe to clear now because our claim was acquired first.
    marker = read_cancel(directory)
    if marker is not None:
        if str(marker.get('attemptId') or '') == str(attempt_id):
            remove_cancel(directory)
            return finish({'ok': False, 'error': 'LSP_CANCELLED'})
        remove_cancel(directory)

    if cancel_matches(directory, attempt_id):
        remove_cancel(directory)
        return finish({'ok': False, 'error': 'LSP_CANCELLED'})

    log_handle = None
    try:
        with open(daemon_path, 'wb') as handle:
            handle.write(daemon_source)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(daemon_path, 0o700)
        log_handle = open(log_path, 'ab')
        log_handle.write(('starting %s\n' % language).encode('utf-8'))
        log_handle.flush()

        process = subprocess.Popen(
            [sys.executable or 'python3', '-u', daemon_path,
             '--socket', sock_path, '--root-uri', root_uri,
             '--server', server_id, '--session', session_key],
            stdin=subprocess.DEVNULL,
            stdout=log_handle,
            stderr=log_handle,
            start_new_session=True,
        )
    except Exception as error:
        if log_handle is not None:
            try:
                log_handle.close()
            except OSError:
                pass
        return finish({'ok': False, 'error': 'LSP_START_FAILED: %s' % error})
    # The child owns the inherited log descriptor; retaining it in this short
    # helper leaks a file handle on every start and makes cleanup warnings
    # nondeterministic.
    log_handle.close()
    if not update_claim(directory, attempt_id, identity or {}, process.pid, 'starting'):
        stopped = terminate_process_group(process.pid)
        try:
            process.wait(timeout=5.0)
        except (OSError, subprocess.TimeoutExpired):
            pass
        return finish({'ok': False,
                       'error': 'LSP_ATTEMPT_OWNERSHIP_MISMATCH' if stopped else 'LSP_STOP_UNCONFIRMED'})

    # Keep an ownership snapshot from the instant the daemon is published.
    # The daemon starts the language server in a separate session, and it may
    # exit before state.json/socket publication (startup failure or abort).
    # A post-exit /proc walk cannot discover a reparented LS, so every polling
    # pass extends this snapshot before handling any exit/cancel path.
    known_pids, known_groups = _process_tree(process.pid)

    def refresh_process_tree():
        current_pids, current_groups = _process_tree(process.pid)
        known_pids.update(current_pids)
        known_groups.update(current_groups)

    def reap_process():
        # terminate_process_group works by PID/group because it also covers
        # detached descendants.  Reap this Popen leader separately so a
        # cancelled or failed startup cannot emit a ResourceWarning or leave a
        # zombie in the helper process.
        try:
            process.wait(timeout=5.0)
        except subprocess.TimeoutExpired:
            pass
        except (OSError, ValueError):
            pass

    deadline = time.time() + LSP_START_TIMEOUT_SEC
    while time.time() < deadline:
        refresh_process_tree()
        if cancel_matches(directory, attempt_id):
            stopped = terminate_process_group(process.pid, (known_pids, known_groups))
            reap_process()
            if not stopped:
                return finish({'ok': False, 'error': 'LSP_ABORT_UNCONFIRMED'})
            remove_cancel(directory)
            try:
                os.remove(sock_path)
            except OSError:
                pass
            return finish({'ok': False, 'error': 'LSP_CANCELLED'})
        if process.poll() is not None:
            stopped = terminate_process_group(process.pid, (known_pids, known_groups))
            reap_process()
            if not stopped:
                return finish({'ok': False, 'error': 'LSP_START_UNCONFIRMED', 'log': tail(log_path)})
            return finish({'ok': False, 'error': 'LSP_START_FAILED', 'log': tail(log_path)})
        if socket_alive(sock_path):
            if cancel_matches(directory, attempt_id):
                refresh_process_tree()
                stopped = terminate_process_group(process.pid, (known_pids, known_groups))
                reap_process()
                if not stopped:
                    return finish({'ok': False, 'error': 'LSP_ABORT_UNCONFIRMED'})
                remove_cancel(directory)
                return finish({'ok': False, 'error': 'LSP_CANCELLED'})
            # A replacement attempt may have published state while this
            # daemon was still negotiating its handshake.  Never overwrite
            # that state; tear down only this process tree and report the
            # ownership conflict to the stale caller.
            if os.path.exists(state_path):
                try:
                    with open(state_path, encoding='utf-8') as handle:
                        existing = json.load(handle)
                except (OSError, ValueError, TypeError):
                    existing = {}
                if str(existing.get('attemptId') or '') != str(attempt_id or ''):
                    stopped = terminate_process_group(process.pid, (known_pids, known_groups))
                    reap_process()
                    return finish({'ok': False,
                                   'error': 'LSP_ATTEMPT_OWNERSHIP_MISMATCH' if stopped else 'LSP_STOP_UNCONFIRMED'})
            temporary = state_path + '.tmp.%s' % os.getpid()
            with open(temporary, 'w', encoding='utf-8') as handle:
                json.dump({'pid': process.pid, 'server': server_id,
                           'rootUri': root_uri, 'socket': sock_path,
                           'attemptId': str(attempt_id or ''),
                           'identity': identity or {}}, handle)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, state_path)
            if not update_claim(directory, attempt_id, identity or {}, process.pid, 'published'):
                stopped = terminate_process_group(process.pid, (known_pids, known_groups))
                reap_process()
                return finish({'ok': False,
                               'error': 'LSP_ATTEMPT_OWNERSHIP_MISMATCH' if stopped else 'LSP_STOP_UNCONFIRMED'})
            return finish({'ok': True, 'socket': sock_path, 'rootUri': root_uri,
                           'pid': process.pid}, keep_claim=True)
        time.sleep(0.1)
    refresh_process_tree()
    stopped = terminate_process_group(process.pid, (known_pids, known_groups))
    reap_process()
    if not stopped:
        return finish({'ok': False, 'error': 'LSP_STOP_UNCONFIRMED', 'log': tail(log_path)})
    return finish({'ok': False, 'error': 'LSP_START_TIMEOUT', 'log': tail(log_path)})


def tail(path, limit=2048):
    try:
        with open(path, 'rb') as handle:
            handle.seek(0, os.SEEK_END)
            size = handle.tell()
            handle.seek(max(0, size - limit))
            return handle.read().decode('utf-8', errors='replace')
    except OSError:
        return ''


def proxy(root, session_key, args):
    directory = session_dir(root, session_key)
    sock_path = os.path.join(directory, 'server.sock')
    if not identity_matches(directory, args):
        return {'ok': False, 'error': 'LSP_SESSION_IDENTITY_MISMATCH'}
    request = {
        'action': 'request',
        'method': args.get('method', ''),
        'params': args.get('params', {}),
        'timeoutSec': float(args.get('timeoutSec', 10.0)),
    }
    if not socket_alive(sock_path):
        return {'ok': False, 'error': 'LSP_UNAVAILABLE'}
    client = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    client.settimeout(request['timeoutSec'] + 5.0)
    try:
        client.connect(sock_path)
        client.sendall((json.dumps(request) + '\n').encode('utf-8'))
        buffer = b''
        while b'\n' not in buffer:
            chunk = client.recv(65536)
            if not chunk:
                break
            buffer += chunk
            if len(buffer) > CONTROL_LIMIT:
                return {'ok': False, 'error': 'LSP_FRAME_LIMIT'}
        if b'\n' not in buffer:
            return {'ok': False, 'error': 'LSP_TIMEOUT'}
        line = buffer.split(b'\n', 1)[0]
        response = json.loads(line.decode('utf-8', errors='replace'))
        return {'ok': True, 'response': response}
    except socket.timeout:
        return {'ok': False, 'error': 'LSP_TIMEOUT'}
    except OSError as error:
        return {'ok': False, 'error': 'LSP_UNAVAILABLE: %s' % error}
    finally:
        client.close()


def stop_daemon(root, session_key, identity=None, attempt_id=''):
    directory = session_dir(root, session_key)
    sock_path = os.path.join(directory, 'server.sock')
    state_path = os.path.join(directory, 'state.json')
    claim = read_claim(directory)
    # An already-absent session is idempotent only when there is no live
    # pre-publication owner.  A claim is intentionally checked before this
    # shortcut so STOPPED cannot be reported while A is still starting.
    if not os.path.exists(sock_path) and not os.path.exists(state_path):
        if claim is not None:
            if not attempt_id:
                return {'ok': False, 'error': 'LSP_ATTEMPT_ID_REQUIRED'}
            if not ATTEMPT_ID_RE.fullmatch(str(attempt_id)):
                return {'ok': False, 'error': 'LSP_ATTEMPT_ID_INVALID'}
            if str(claim.get('attemptId') or '') != str(attempt_id):
                return {'ok': False, 'error': 'LSP_SESSION_IDENTITY_MISMATCH'}
            claim_identity = claim.get('identity') or {}
            expected_identity = identity or {}
            if any(str(claim_identity.get(key, '')) != str(expected_identity.get(key, ''))
                   for key in ('rootTaskId', 'projectId', 'rootGeneration')):
                return {'ok': False, 'error': 'LSP_SESSION_IDENTITY_MISMATCH'}
            if claim_is_live(claim):
                return {'ok': False, 'error': 'LSP_STOP_UNCONFIRMED'}
            remove_claim(directory, attempt_id)
        return {'ok': True, 'stopped': True}
    # A published socket without helper-owned state cannot prove which process
    # group owns it.  Refuse to call that STOPPED or replace it, even if the
    # socket happens to answer an acknowledgement.
    if os.path.exists(sock_path) and not os.path.exists(state_path):
        return {'ok': False, 'error': 'LSP_STATE_MISSING'}
    if attempt_id and not ATTEMPT_ID_RE.fullmatch(str(attempt_id)):
        return {'ok': False, 'error': 'LSP_ATTEMPT_ID_INVALID'}
    if not attempt_id:
        # A live state without an exact attempt owner cannot be safely stopped:
        # a delayed cleanup from an older invocation must never target a
        # replacement session.
        return {'ok': False, 'error': 'LSP_ATTEMPT_ID_REQUIRED'}
    expected = dict(identity or {})
    expected['attemptId'] = str(attempt_id)
    if not identity_matches(directory, expected):
        return {'ok': False, 'error': 'LSP_SESSION_IDENTITY_MISMATCH'}
    state_pid = None
    try:
        with open(state_path, encoding='utf-8') as handle:
            state_pid = json.load(handle).get('pid')
    except (OSError, ValueError, TypeError):
        pass
    if not state_pid:
        # A state record without its daemon owner cannot be reconciled with a
        # possibly detached language-server group.  Keep the record and fail
        # closed instead of deleting evidence and publishing a replacement.
        return {'ok': False, 'error': 'LSP_STATE_INVALID'}
    # Capture daemon + language-server groups before asking the daemon to stop.
    # The daemon can exit immediately after sending its acknowledgement, at
    # which point a post-exit /proc walk would otherwise lose the orphaned LS
    # group entirely.
    initial_tree = _process_tree(state_pid) if state_pid else (set(), set())
    if not os.path.exists(sock_path):
        if not initial_tree[0] and not process_alive(state_pid):
            # The owner already disappeared before we could capture its
            # descendants.  There is no proof that an independently-sessioned
            # language server is gone, so STOPPED must remain unavailable.
            return {'ok': False, 'error': 'LSP_STOP_UNCONFIRMED'}
        if state_pid and process_alive(state_pid):
            if not terminate_process_group(state_pid, initial_tree):
                return {'ok': False, 'error': 'LSP_STOP_TIMEOUT'}
        if state_pid and (process_alive(state_pid) or
                          not _targets_gone(*initial_tree)):
            return {'ok': False, 'error': 'LSP_STOP_TIMEOUT'}
        try:
            os.remove(state_path)
        except OSError:
            pass
        remove_claim(directory, attempt_id)
        return {'ok': True, 'stopped': True}
    client = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    client.settimeout(LSP_STOP_TIMEOUT_SEC)
    try:
        client.connect(sock_path)
        client.sendall(b'{"action":"stop"}\n')
        try:
            response = client.recv(4096)
            if b'stopped' not in response:
                return {'ok': False, 'error': 'LSP_STOP_UNCONFIRMED'}
        except OSError:
            return {'ok': False, 'error': 'LSP_STOP_UNCONFIRMED'}
    except OSError:
        return {'ok': False, 'error': 'LSP_STOP_UNCONFIRMED'}
    finally:
        client.close()
    deadline = time.time() + LSP_STOP_TIMEOUT_SEC
    while os.path.exists(sock_path) and time.time() < deadline:
        time.sleep(0.05)
    if os.path.exists(sock_path):
        return {'ok': False, 'error': 'LSP_STOP_TIMEOUT'}
    # The daemon sends "stopped" only after its language-server process group
    # has exited.  Re-run the helper-owned tree barrier as well: this catches
    # a daemon that acknowledged before its finally block completed and proves
    # that independent LS groups are gone even if the daemon PID disappeared.
    if state_pid and not terminate_process_group(state_pid, initial_tree):
        return {'ok': False, 'error': 'LSP_STOP_TIMEOUT'}
    if state_pid and (process_alive(state_pid) or
                      not _targets_gone(*initial_tree)):
        return {'ok': False, 'error': 'LSP_STOP_TIMEOUT'}
    try:
        os.remove(state_path)
    except OSError:
        pass
    remove_claim(directory, attempt_id)
    return {'ok': True, 'stopped': True}


def abort_daemon(root, session_key, identity=None, attempt_id=''):
    """Durably cancel a dispatched start/request and confirm group teardown."""
    directory = session_dir(root, session_key)
    sock_path = os.path.join(directory, 'server.sock')
    state_path = os.path.join(directory, 'state.json')
    if not attempt_id:
        return {'ok': False, 'error': 'LSP_ATTEMPT_ID_REQUIRED'}
    if not ATTEMPT_ID_RE.fullmatch(str(attempt_id)):
        return {'ok': False, 'error': 'LSP_ATTEMPT_ID_INVALID'}
    claim_before = read_claim(directory)
    had_existing_session = (
        os.path.exists(sock_path) or os.path.exists(state_path) or
        claim_before is not None
    )
    if os.path.exists(state_path) or claim_before is not None:
        expected = dict(identity or {})
        expected['attemptId'] = str(attempt_id)
        if not identity_matches(directory, expected):
            return {'ok': False, 'error': 'LSP_SESSION_IDENTITY_MISMATCH'}
    write_cancel(directory, attempt_id, identity or {})
    stopped = stop_daemon(root, session_key, identity, attempt_id)
    if stopped.get('ok') and stopped.get('stopped'):
        if had_existing_session:
            remove_cancel(directory)
        return {'ok': True, 'stopped': True, 'cancelRequested': True}

    # A live pre-publication claim is not an idempotent absent session.  Keep
    # the marker, wait for A to consume it and prove its complete process-group
    # teardown, and refuse success while an owner is still unconfirmed.  This
    # is deliberately a bounded wait so a crashed helper leaves an explicit
    # unconfirmed result rather than silently handing ownership to B.
    if read_claim(directory) is not None:
        deadline = time.time() + LSP_START_TIMEOUT_SEC + LSP_STOP_TIMEOUT_SEC + 5.0
        while time.time() < deadline:
            if os.path.exists(sock_path) or os.path.exists(state_path):
                stopped = stop_daemon(root, session_key, identity, attempt_id)
                if stopped.get('ok') and stopped.get('stopped'):
                    remove_cancel(directory)
                    return {'ok': True, 'stopped': True, 'cancelRequested': True}
            claim = read_claim(directory)
            if claim is None:
                if not os.path.exists(sock_path) and not os.path.exists(state_path):
                    remove_cancel(directory)
                    return {'ok': True, 'stopped': True, 'cancelRequested': True}
                break
            if str(claim.get('attemptId') or '') != str(attempt_id):
                # A replacement owner appeared before A's cancellation was
                # confirmed.  Never remove its marker or claim success.
                return {'ok': False, 'error': 'LSP_SESSION_IDENTITY_MISMATCH',
                        'cancelRequested': True}
            time.sleep(0.05)
        return {'ok': False, 'error': 'LSP_ABORT_UNCONFIRMED',
                'cancelRequested': True}

    # No owner and no publication is a valid pre-dispatch cancellation.  Keep
    # the marker for the exact future start attempt to consume.
    if not os.path.exists(sock_path) and not os.path.exists(state_path):
        return {'ok': True, 'stopped': True, 'cancelRequested': True}
    return {'ok': False, 'error': stopped.get('error', 'LSP_ABORT_UNCONFIRMED'),
            'cancelRequested': True}


def identity_matches(directory, expected):
    """Validate the immutable project/root binding saved at start."""
    keys = ('rootTaskId', 'projectId', 'rootGeneration', 'attemptId')
    if not expected or not any(expected.get(k) not in (None, '', 0) for k in keys):
        return True
    try:
        state_path = os.path.join(directory, 'state.json')
        if os.path.exists(state_path):
            with open(state_path, encoding='utf-8') as handle:
                state = json.load(handle)
        else:
            state = read_claim(directory)
            if state is None:
                return False
        actual = state.get('identity') or {}
        if not all(str(actual.get(k, '')) == str(expected.get(k, ''))
                   for k in ('rootTaskId', 'projectId', 'rootGeneration')):
            return False
        expected_attempt = expected.get('attemptId')
        if expected_attempt not in (None, ''):
            return str(state.get('attemptId') or '') == str(expected_attempt)
        return True
    except (OSError, ValueError):
        return False


def status_daemon(root, session_key):
    directory = session_dir(root, session_key)
    sock_path = os.path.join(directory, 'server.sock')
    alive = socket_alive(sock_path)
    return {'ok': True, 'alive': alive}


