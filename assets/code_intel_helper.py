def run_operation(config, source_reader):
    identity = config['workspaceId']
    if not re.fullmatch(r'[0-9a-f]{24}', identity):
        raise ValueError('INVALID_WORKSPACE_ID')
    root = WORKSPACE_ROOT + identity
    if not os.path.isdir(root) or os.path.islink(root):
        raise ValueError('MIRROR_NOT_PREPARED')

    operation = config['operation']
    args = config.get('args') or {}

    if operation == 'probe':
        python_ok = sys.version_info[:2] >= (3, 6)
        return {'ok': True, 'python': sys.version.split()[0], 'pythonOk': python_ok,
                'sqlite3': True, 'root': root}

    if operation == 'index_build':
        rel_paths = [clean(p) for p in (args.get('files') or [])]
        candidate = os.path.join(code_intel_dir(root), 'candidate.sqlite3')
        stats = build_snapshot(os.path.join(root, 'project'), candidate, rel_paths)
        stats['ok'] = True
        return stats

    if operation == 'lsp_start':
        daemon_source = source_reader(0)
        identity_fields = {key: args.get(key, '') for key in ('rootTaskId', 'projectId', 'rootGeneration')}
        return start_daemon(root, args['sessionKey'], daemon_source,
                            args['server'], config.get('token'), args.get('language', ''), identity_fields,
                            args.get('attemptId', ''))

    if operation == 'lsp_request':
        return proxy(root, args['sessionKey'], args)

    if operation == 'lsp_stop':
        identity_fields = {key: args.get(key, '') for key in ('rootTaskId', 'projectId', 'rootGeneration')}
        return stop_daemon(root, args['sessionKey'], identity_fields, args.get('attemptId', ''))

    if operation == 'lsp_abort':
        identity_fields = {key: args.get(key, '') for key in ('rootTaskId', 'projectId', 'rootGeneration')}
        return abort_daemon(root, args['sessionKey'], identity_fields, args.get('attemptId', ''))

    if operation == 'lsp_status':
        return status_daemon(root, args['sessionKey'])

    return {'ok': False, 'error': 'UNKNOWN_OPERATION: %s' % operation}


def main():
    # Termux provides fcntl.flock for the short-lived P3 workspace critical
    # sections.  Keep the import local so the Windows offline helper tests can
    # still exercise the pure parser/daemon functions without a POSIX module.
    try:
        import fcntl  # noqa: F401
    except ImportError:  # pragma: no cover - Windows-only test host
        fcntl = None
    url = sys.argv[1]
    if not re.fullmatch(r'http://127\.0\.0\.1:[0-9]+/[a-f0-9]{64}', url):
        raise ValueError('INVALID_RPC_URL')
    http = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    def fetch(route):
        return http.open(url + '/' + route, timeout=30)

    with fetch('control') as response:
        payload = response.read(CONTROL_LIMIT + 1)
    if len(payload) > CONTROL_LIMIT:
        raise ValueError('CONTROL_LIMIT')
    config = json.loads(payload)

    def source_reader(index):
        with fetch('source/%d' % index) as response:
            return response.read(CONTROL_LIMIT + 1)

    try:
        result = run_operation(config, source_reader)
    except Exception as error:  # fail closed, always answer the bridge
        result = {'ok': False, 'error': '%s: %s' % (error.__class__.__name__, error)}

    encoded = json.dumps(result).encode('utf-8')
    if len(encoded) > CONTROL_LIMIT:
        encoded = b'{"ok":false,"error":"CODE_INTEL_CONTROL_LIMIT"}'
    with http.open(urllib.request.Request(url + '/result', data=encoded, method='POST'),
                   timeout=30) as response:
        response.read()


if __name__ == '__main__':
    main()

